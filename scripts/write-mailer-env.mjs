/**
 * Writes the contact mailer's server settings into out/api/env.php.
 *
 * Reads CONTACT_*, SMTP_* and TURNSTILE_SECRET_KEY (plus NEXT_PUBLIC_SITE_URL
 * as a fallback site address) from the project's .env files, using the same
 * loader and precedence as Next.js (.env.production.local > .env.local >
 * .env.production > .env).
 *
 * Why a .php file and not a copy of .env: if anyone requests env.php in a
 * browser, PHP runs it and outputs nothing, on any server. A plain .env in the
 * web root would be downloadable wherever .htaccess isn't honoured.
 *
 * Runs automatically at the end of `npm run build`; also runnable on its own:
 *   node scripts/write-mailer-env.mjs
 */
import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'
import nextEnv from '@next/env'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const KEY = /^(CONTACT_|SMTP_|TURNSTILE_SECRET_KEY$|NEXT_PUBLIC_SITE_URL$)/

// PHP single-quoted string: only backslash and quote need escaping
const php = (value) => `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`

/**
 * A value exactly as written in a .env line: no $VARIABLE substitution.
 * Next.js expands `$name` in .env values, which silently changes passwords
 * like `Ab$cd#9` (it becomes `Ab`). Mailer settings are read literally
 * instead, with the same rules as the PHP side: quotes are stripped (in double
 * quotes, \$ and \" are unescaped); unquoted values end at a ` #` comment.
 */
const literalFromFile = (contents, key) => {
  let found
  for (const line of contents.split(/\r?\n/)) {
    const match = line.match(new RegExp(`^\\s*(?:export\\s+)?${key}\\s*=\\s*(.*)$`))
    if (!match) continue
    let value = match[1].trim()
    const quoted = value.match(/^(["'])([\s\S]*)\1$/)
    if (quoted) {
      value = quoted[1] === '"' ? quoted[2].replace(/\\([$"\\])/g, '$1') : quoted[2]
    } else {
      value = value.replace(/\s+#.*$/, '').trim()
    }
    found = value // the last definition in a file wins, as in dotenv
  }
  return found
}

export async function writeMailerEnv({ outDir = path.join(ROOT, 'out') } = {}) {
  // Real environment variables (e.g. set in CI) take precedence over .env files
  const preset = new Set(Object.keys(process.env).filter((key) => KEY.test(key)))
  const { loadedEnvFiles = [] } = nextEnv.loadEnvConfig(ROOT, false, { info: () => {}, error: console.error })

  const values = {}
  for (const [key, value] of Object.entries(process.env)) {
    if (!KEY.test(key) || value === undefined) continue
    let literal
    if (!preset.has(key) && key !== 'NEXT_PUBLIC_SITE_URL') {
      // loadedEnvFiles is in priority order: the first file defining the key wins
      for (const file of loadedEnvFiles) {
        literal = literalFromFile(file.contents || '', key)
        if (literal !== undefined) break
      }
    }
    const finalValue = literal ?? value
    if (literal !== undefined && literal !== value) {
      console.warn(`[mailer] ${key} contains characters .env loading would change ($ or #); using it exactly as written (${finalValue.length} characters).`)
    }
    if (finalValue !== '') values[key] = finalValue
  }

  const entries = Object.entries(values).sort(([a], [b]) => a.localeCompare(b))

  const missing = ['SMTP_HOST', 'CONTACT_FROM_EMAIL'].filter((key) => !values[key])
  if (missing.length) {
    console.warn(`[mailer] Not set in .env: ${missing.join(', ')}. The contact form will reply "not configured" until they are.`)
  }

  const body = entries.map(([key, value]) => `    ${php(key)} => ${php(value)},`).join('\n')
  const file = `<?php\n// Generated by scripts/write-mailer-env.mjs from the project's .env. Do not edit or commit.\n// Executing this file prints nothing, so it is safe in the web root.\nreturn [\n${body}\n];\n`

  const target = path.join(outDir, 'api', 'env.php')
  await mkdir(path.dirname(target), { recursive: true })
  await writeFile(target, file, { mode: 0o640 })
  console.log(`[mailer] Wrote ${path.relative(ROOT, target)} (${entries.length} settings${values.SMTP_PASSWORD ? `, password included (${values.SMTP_PASSWORD.length} characters)` : ''}).`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeMailerEnv().catch((error) => {
    console.error(error)
    process.exitCode = 1
  })
}
